function M.Get_greeting()
	local hour = os.date("*t").hour
	local greetings
	local emoji

	if hour < 12 then
		greetings = M.good_morning
	elseif hour < 18 then
		greetings = M.good_afternoon
	else
		greetings = M.good_evening
	end

	math.randomseed(os.time())
	local chosen = greetings[math.random(1, #greetings)]
	local quote = M.motivational_quotes[math.random(1, #M.motivational_quotes)]
	chosen = chosen .. "\n" .. quote
	return { chosen }
end

